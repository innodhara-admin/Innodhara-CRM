"""Deliverables, invoices, payments and vendors (Data Model §6.7–6.10)."""
from __future__ import annotations

from datetime import datetime
from typing import Any

from sqlalchemy import JSON, DateTime, Float, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models.base import OrgScopedMixin, PKMixin, TimestampMixin


class Deliverable(Base, PKMixin, TimestampMixin, OrgScopedMixin):
    """One version of one artifact a project produces (Data Model §6.7).

    Two equal births: generated by the Document Engine, or uploaded by a
    person — the rest of the machine treats both identically.
    """

    __tablename__ = "deliverables"
    __table_args__ = (Index("ix_deliverables_proj_type", "project_id", "type", "version"),)

    project_id: Mapped[str] = mapped_column(String(32), index=True, nullable=False)
    # proposal | syllabus | schedule | invoice | daily_report | closure_report
    # | certificates | feedback_summary | photo_set | other
    type: Mapped[str] = mapped_column(String(30), nullable=False)
    title: Mapped[str | None] = mapped_column(String(300))
    file_path: Mapped[str | None] = mapped_column(String(500))
    content_md: Mapped[str | None] = mapped_column(Text)  # for text artifacts
    version: Mapped[int] = mapped_column(Integer, default=1)
    source: Mapped[str] = mapped_column(String(20), default="ai_generated")  # |manual_upload
    uploaded_by: Mapped[str | None] = mapped_column(String(32))
    # draft | internal_review | approved | sent | accepted
    status: Mapped[str] = mapped_column(String(20), default="draft")
    linked_action_item_id: Mapped[str | None] = mapped_column(String(32))


class Invoice(Base, PKMixin, TimestampMixin, OrgScopedMixin):
    """One invoice of one project — amounts always derived (Data Model §6.8)."""

    __tablename__ = "invoices"
    __table_args__ = (Index("ix_invoices_org_status", "org_id", "status", "due_date"),)

    project_id: Mapped[str] = mapped_column(String(32), index=True, nullable=False)
    kind: Mapped[str] = mapped_column(String(10), default="full")  # advance|balance|full
    amount: Mapped[float] = mapped_column(Float, nullable=False)
    currency: Mapped[str] = mapped_column(String(10), default="INR")
    # The computation, kept: e.g. "110000 + 45000 - 55000 = 100000"
    computation: Mapped[str | None] = mapped_column(Text)
    due_date: Mapped[datetime | None] = mapped_column(DateTime)
    # draft | sent | part_paid | paid | overdue | disputed
    status: Mapped[str] = mapped_column(String(20), default="draft", nullable=False)
    sent_to_stakeholder_id: Mapped[str | None] = mapped_column(String(32))
    pdf_path: Mapped[str | None] = mapped_column(String(500))
    sent_message_id: Mapped[str | None] = mapped_column(String(32))
    sent_at: Mapped[datetime | None] = mapped_column(DateTime)
    # Payment-ladder bookkeeping: which schedule offsets have already fired.
    ladder_fired: Mapped[list[int]] = mapped_column(JSON, default=list)


class Payment(Base, PKMixin, TimestampMixin, OrgScopedMixin):
    """One payment actually received against an invoice (Data Model §6.9)."""

    __tablename__ = "payments"

    invoice_id: Mapped[str] = mapped_column(String(32), index=True, nullable=False)
    amount: Mapped[float] = mapped_column(Float, nullable=False)
    received_on: Mapped[datetime | None] = mapped_column(DateTime)
    method: Mapped[str | None] = mapped_column(String(20))  # cheque|transfer|upi|cash
    recorded_by: Mapped[str | None] = mapped_column(String(32))
    note: Mapped[str | None] = mapped_column(Text)


class Vendor(Base, PKMixin, TimestampMixin, OrgScopedMixin):
    """One outside supplier plans can depend on (Data Model §6.10)."""

    __tablename__ = "vendors"

    name: Mapped[str] = mapped_column(String(200), nullable=False)
    contact_name: Mapped[str | None] = mapped_column(String(200))
    phone: Mapped[str | None] = mapped_column(String(30))
    email: Mapped[str | None] = mapped_column(String(320))
    category: Mapped[str | None] = mapped_column(String(100))
    notes: Mapped[str | None] = mapped_column(Text)
