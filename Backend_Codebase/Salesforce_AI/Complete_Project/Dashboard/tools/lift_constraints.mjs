/**
 * Lift the constraints openapi-zod-client drops (07_BUILD_PLAN.md P2 / A3).
 *
 * FastAPI renders `int | None = Field(ge=1, le=100)` as
 *   anyOf: [{type: integer, minimum: 1, maximum: 100}, {type: null}]
 * and openapi-zod-client@1.18.3 emits `z.union([z.number(), z.null()])` for
 * that — the bounds are gone. Constraints survive only on required,
 * non-nullable fields.
 *
 * Measured on this spec: 12 survive, 16 are dropped. Every dropped rule IS
 * enforced by the server, so a descriptor may not call it `ui-only` ("the
 * server accepts anything") without lying. This file recovers them from
 * openapi.json, which has them all, so `backend-undeclared` rules stay derived
 * rather than hand-typed.
 */
import { readFileSync, writeFileSync } from "node:fs";

const KEYS = [
  "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
  "minLength", "maxLength", "pattern", "minItems", "maxItems",
];

/** Constraints declared directly on the property — these DO reach generated.ts. */
function direct(prop) {
  const out = {};
  for (const k of KEYS) if (prop?.[k] !== undefined) out[k] = prop[k];
  return out;
}

/**
 * Everything declared anywhere on the property, including inside anyOf
 * branches. A branch value never overwrites a directly-declared one: the
 * direct declaration is what the server's own schema says at the top level.
 */
function merged(prop) {
  const out = direct(prop);
  for (const branch of prop?.anyOf ?? []) {
    for (const [k, v] of Object.entries(direct(branch))) {
      if (out[k] === undefined) out[k] = v;
    }
  }
  return out;
}

export function lift(spec) {
  const table = {};
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    const fields = {};
    for (const [field, prop] of Object.entries(schema.properties ?? {})) {
      const rules = merged(prop);
      if (Object.keys(rules).length) fields[field] = rules;
    }
    if (Object.keys(fields).length) table[name] = fields;
  }
  return table;
}

/** Only the rules the generator loses: in an anyOf branch, not on the property. */
export function droppedOnly(spec) {
  const table = {};
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    for (const [field, prop] of Object.entries(schema.properties ?? {})) {
      const survives = Object.keys(direct(prop)).length > 0;
      const all = merged(prop);
      if (!survives && Object.keys(all).length) {
        (table[name] ??= {})[field] = all;
      }
    }
  }
  return table;
}

export function render(spec) {
  const table = lift(spec);
  const dropped = droppedOnly(spec);
  const droppedCount = Object.values(dropped)
    .reduce((n, fields) => n + Object.keys(fields).length, 0);
  const totalCount = Object.values(table)
    .reduce((n, fields) => n + Object.keys(fields).length, 0);

  return (
    "// GENERATED by Dashboard/tools/lift_constraints.mjs — do not edit.\n" +
    "// Source: src/api/openapi.json.\n" +
    "//\n" +
    "// Every constraint the spec declares, including the ones\n" +
    "// openapi-zod-client drops because they sit inside an anyOf branch\n" +
    "// (07_BUILD_PLAN.md P2). Descriptors read bounds from here, never by hand.\n" +
    `// At generation time: ${totalCount} constrained fields, of which ` +
    `${droppedCount} are\n// absent from generated.ts and reachable ONLY through this table.\n` +
    `export const CONSTRAINTS = ${JSON.stringify(table, null, 2)} as const;\n\n` +
    "// The subset the generator loses. Named separately so a test can assert\n" +
    "// the lift is still carrying them rather than quietly emitting {}.\n" +
    `export const DROPPED_BY_GENERATOR = ${JSON.stringify(dropped, null, 2)} as const;\n`
  );
}

export function liftFile(specPath, outPath) {
  const spec = JSON.parse(readFileSync(specPath, "utf-8"));
  writeFileSync(outPath, render(spec), { encoding: "utf-8" });
  return spec;
}
